export const LanguageProvider = ({ children }) => {
  const [lang, setLang] = useState(
    () => localStorage.getItem("sentinel_lang") || "fa"
  );

  const value = useMemo(() => {
    const t = (keyPath) => {
      const keys = keyPath.split(".");
      let current = DICTIONARY[lang];
      keys.forEach((key) => {
        current = current?.[key];
      });
      if (current !== undefined && current !== null) return current;
      let fallback = DICTIONARY.en;
      keys.forEach((key) => {
        fallback = fallback?.[key];
      });
      return fallback || keyPath;
    };
    return { lang, setLang, t };
  }, [lang]);

  const updateLang = (next) => {
    const value = next || "fa";
    try {
      localStorage.setItem("sentinel_lang", value);
    } catch {
    }
    setLang(value);
  };

  return (
    <LanguageContext.Provider value={{ ...value, setLang: updateLang }}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useI18n = () => useContext(LanguageContext);
